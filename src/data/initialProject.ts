const bootTime = Date.now()

function history(base: number, amp: number, phase: number, count = 90): PointHistoryPoint[] {
  return Array.from({ length: count }, (_, index) => {
    const distance = count - 1 - index
    const wave =
      Math.sin(index * 0.26 + phase) * amp +
      Math.sin(index * 0.09 + phase * 1.7) * amp * 0.35 +
      Math.cos(index * 0.61 + phase * 0.5) * amp * 0.1
    return {
      t: bootTime - distance * 4000,
      v: Number((base + wave).toFixed(3)),
    }
  })
}

interface PointSeed {
  id: string
  name: string
  device: string
  pointType: PointType
  unit?: string
  value: PointValue
  min?: number
  max?: number
  precision?: number
  writable?: boolean
  options?: PointOption[]
  boolLabels?: [string, string]
  amp?: number
  phase?: number
}

function makePoint(seed: PointSeed): PointDefinition {
  const numeric = typeof seed.value === 'number'
  const bool = typeof seed.value === 'boolean'
  const numericValue = typeof seed.value === 'number' ? seed.value : 0
  const precision = seed.precision ?? (numeric ? 1 : 0)
  return {
    id: seed.id,
    name: seed.name,
    device: seed.device,
    pointType: seed.pointType,
    unit: seed.unit ?? '',
    value: seed.value,
    min: seed.min ?? 0,
    max: seed.max ?? 100,
    precision,
    writable: Boolean(seed.writable),
    quality: 'good',
    options: seed.options,
    boolLabels: seed.boolLabels,
    history: numeric
      ? history(numericValue, seed.amp ?? 0.4, seed.phase ?? 0.5)
      : Array.from({ length: 90 }, (_, index) => ({
          t: bootTime - (89 - index) * 4000,
          v: bool ? (seed.value ? 1 : 0) : 0,
        })),
    sim: numeric && !seed.writable
      ? {
          base: numericValue,
          amp: seed.amp ?? 0.4,
          speed: 0.05 + (seed.phase ?? 0) * 0.004,
          phase: seed.phase ?? 0.5,
        }
      : undefined,
  }
}

