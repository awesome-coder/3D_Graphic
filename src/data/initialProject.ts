interface NodeSeed {
  id: string
  type: GraphNode['type']
  tag: string
  label: string
  x: number
  y: number
  w?: number
  h?: number
  style?: Partial<NodeStyle>
  props?: Partial<NodeProps>
  point?: string | null
  mode?: NodeBinding['mode']
}

function makeNode(seed: NodeSeed): GraphNode {
  const base = createGraphNode(seed.type, seed.x, seed.y, [])
  return {
    ...base,
    id: seed.id,
    tag: seed.tag,
    label: seed.label,
    x: seed.x,
    y: seed.y,
    w: seed.w ?? base.w,
    h: seed.h ?? base.h,
    style: { ...base.style, ...seed.style },
    props: { ...base.props, ...seed.props },
    binding: {
      pointId: seed.point ?? null,
      mode: seed.mode ?? 'value',
    },
  }
}

